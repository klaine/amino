def table_short_names(names):
    """Four-character, unique enum-square labels for the wavetable list."""
    out, used = [], set()
    for n in names:
        base = n[:4]
        cand, k = base, 2
        while cand in used:
            suffix = str(k)
            cand = n[:4 - len(suffix)] + suffix
            k += 1
        used.add(cand)
        out.append(cand)
    return out


def fit_short_options(options, labels):
    """Keep enum-square labels at four chars max and disambiguate collisions."""
    out, used = [], set()
    for option, label in zip(options, labels):
        candidate = str(label)[:4]
        k = 2
        while candidate in used:
            suffix = str(k)
            stem = str(label)[:max(0, 4 - len(suffix))]
            candidate = (stem + suffix)[:4]
            if not candidate:
                candidate = str(k)[-4:]
            k += 1
        used.add(candidate)
        out.append(candidate)
    return out


def short_options(p):
    if p["kind"] != "enum":
        return None
    opts = tuple(p["opts"])
    if p.get("tables"):
        raw = table_short_names(p["opts"])
    else:
        raw = SHORT_OPTS.get(opts, list(opts))
    return fit_short_options(p["opts"], raw)


def chain_entry(p, key):
    short = p["short"]
    # Give each modulation slot a distinct cell label in the shared contract;
    # this avoids repeating labels when two slots share one page.
    mm = re.match(r"m([1-8])_(src|dst|amt|via|via_depth)$", key)
    if mm:
        short = {"src": "Src", "dst": "Dst", "amt": "Amt", "via": "Via",
                 "via_depth": "VD"}[mm.group(2)] + mm.group(1)
    d = {"key": key, "name": p["name"], "short_name": short, "type": p["kind"]}
    if p["kind"] == "enum":
        d["options"] = list(p["opts"])
        so = short_options(p)
        if so and so != list(p["opts"]):
            d["short_options"] = so
        d["default"] = p["default"]
    else:
        d["min"] = p.get("mn", 0)
        d["max"] = p.get("mx", 1)
        d["default"] = p["default"]
        if p["kind"] == "int":
            d["step"] = 1
        elif p.get("step") is not None:
            d["step"] = p["step"]
        if p.get("unit"):
            d["unit"] = p["unit"]
    v = VIZ.get(p.get("viz"))
    if v:
        d["viz"] = v
    if p.get("live"):
        d["live"] = True
    if p.get("big"):
        d["display"] = "big"
    if p.get("card"):
        d["card_script"] = p["card"]
        d["card_w"] = 112
        d["card_h"] = 48
    return d


