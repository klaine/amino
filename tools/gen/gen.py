    h.append("typedef struct {")
    h.append("    const char *key; const char *name; const char *short_name;")
    h.append("    const char *unit; uint8_t kind; uint8_t scope; uint16_t offset;")
    h.append("    float min, max, def;")
    h.append("    const char *const *options; uint8_t option_count; uint8_t flags;")
