def emit_help_page_guides(chain_params, levels):
    """Add a compact knob-order leaf for each hierarchy page to help.json.

    Existing authored prose is preserved; only pages without a matching leaf
    are added, so running the generator repeatedly is idempotent.
    """
    path = os.path.join(ROOT, "src", "help.json")
    with open(path, "r", encoding="utf-8") as f:
        help_tree = json.load(f)
    pages = next((c for c in help_tree.get("children", [])
                  if c.get("title") == "Pages"), None)
    if pages is None:
        return
    children = pages.setdefault("children", [])
    known = {c.get("title") for c in children}
    meta = {p["key"]: p for p in chain_params}
    changed = False

    for level in levels.values():
        knobs = level.get("knobs", [])
        is_selector = any(level.get(k) for k in ("list_param", "items_param"))
        if not knobs and not is_selector:
            continue
        title = level.get("name", "Page")
        if title in known:
            continue

        local = {e["key"]: e for e in level.get("params", [])
                 if isinstance(e, dict) and "key" in e}
        labels = []
        for knob in knobs:
            key = knob if isinstance(knob, str) else knob.get("key")
            entry = local.get(key, meta.get(key, {}))
            labels.append(entry.get("short_name") or entry.get("name") or key)

        lines = []
        if labels:
            for row_start in (0, 4):
                row = labels[row_start:row_start + 4]
                if not row:
                    continue
                for i in range(0, len(row), 2):
                    a = row[i]
                    n = row_start + i + 1
                    if i + 1 < len(row):
                        lines.append("%d %s  %d %s" % (n, a, n + 1, row[i + 1]))
                    else:
                        lines.append("%d %s" % (n, a))
                if row_start == 0 and len(labels) > 4:
                    lines.append("")
        elif level.get("list_param"):
            lines = ["Browse preset bank.", "Jog selects; click", "to audition."]
        else:
            lines = ["Choose a factory", "preset and layer.",
                     "It loads into the", "focused layer."]
        if level.get("child_count"):
            lines.extend(["", "Edits the focused", "layer."])
        children.append({"title": title, "lines": lines})
        known.add(title)
        changed = True

    if changed:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            json.dump(help_tree, f, ensure_ascii=True, indent=4)
            f.write("\n")


def factory_files():
    d = os.path.join(ROOT, "presets", "factory")
    return sorted(os.path.join(d, f) for f in os.listdir(d) if f.endswith(".json"))


def encode_value(p, v):
    if p["kind"] == "enum":
        if isinstance(v, str):
            if v in p["opts"]:
                return float(p["opts"].index(v))
            raise ValueError("bad enum %r for %s" % (v, p["key"]))
        return float(v)
    return float(v)


def emit_layer_sources(presets):
    """Compile the Load Layer items list: every non-empty layer of every preset.

    A layer is offered when the preset sets a key for it, or when the preset's
    layer_count includes it (its defaults are then real sound).  Built here so
    get_param only copies a prepared string.
    """
    rows = []
    for idx, (j, _vals) in enumerate(presets):
        params = j.get("params", {})
        count = int(params.get("layer_count", 1))
        used = set(range(1, count + 1))
        for key in params:
            m = re.match(r"^l([1-4])_", key)
            if m:
                used.add(int(m.group(1)))
        name = j.get("name", "Preset %d" % idx)
        for n in sorted(used):
            if 1 <= n <= 4:
                rows.append((idx, n, "%s/L%d" % (name, n)))
    c = []
    c.append("")
    c.append("const AminoLayerSource amino_layer_sources[] = {")
    for idx, n, label in rows:
        c.append("    { %d, %d, %s }," % (idx, n, cstr(label)))
    c.append("};")
    c.append("const int amino_layer_source_count = %d;" % len(rows))
    c.append("const char amino_layer_src_list_json[] = %s;" %
             cstr(json.dumps([r[2] for r in rows], separators=(",", ":"))))
    return c, rows


def emit_presets():
    presets = []
    for path in factory_files():
        with open(path, "r", encoding="utf-8") as f:
            j = json.load(f)
        vals = []
        for key, v in j.get("params", {}).items():
            m = re.match(r"^l([1-4])_(.+)$", key)
            if m:
                n, bare = int(m.group(1)), m.group(2)
                if bare not in P.LAYER_BY_KEY:
                    print("WARN unknown layer key", key, "in", os.path.basename(path))
                    continue
                pid = 0x8000 | ((n - 1) << 9) | P.LAYER_BY_KEY[bare]
                p = P.LAYER[P.LAYER_BY_KEY[bare]]
            else:
                if key == "flavour":
                    # docs 09/10 predate the platform-forced rename of the
                    # global flavour key (see docs/15-implementation-notes.md).
                    key = "flavour_global"
                if key not in P.GLOBAL_BY_KEY:
                    print("WARN unknown global key", key, "in", os.path.basename(path))
                    continue
                pid = P.GLOBAL_BY_KEY[key]
                p = P.GLOBAL[pid]
            try:
                vals.append((pid, encode_value(p, v)))
            except ValueError as e:
                print("WARN", e, "in", os.path.basename(path))
        presets.append((j, vals))

    c = []
    c.append("/* Generated by tools/gen/gen.py - do not edit. */")
    c.append('#include "factory_presets.h"')
    c.append("")
    for i, (j, vals) in enumerate(presets):
        c.append("static const AminoPresetValue preset_values_%d[] = {" % i)
        for pid, v in vals:
            c.append("    { %d, %.6ff }," % (pid, v))
        if not vals:
            c.append("    { 0, 0.0f },")
        c.append("};")
    c.append("const AminoFactoryPreset amino_factory_presets[] = {")
    for i, (j, vals) in enumerate(presets):
        c.append('    { %s, %s, %s, %s, %sf, %d, preset_values_%d },'
                 % (cstr(j.get("name", "Preset %d" % i)),
                    cstr(j.get("bank", "")), cstr(j.get("category", "")),
                    cstr(j.get("description", "")),
                    ("%.2f" % float(j.get("bpm", 120))), len(vals), i))
    c.append("};")
    c.append("const int amino_factory_preset_count = %d;" % len(presets))
    layer_c, rows = emit_layer_sources(presets)
    c.extend(layer_c)
    preset_names = [j.get("name", "Preset %d" % i)
                    for i, (j, _vals) in enumerate(presets)]
    c.append("const char amino_preset_list_json[] = %s;" %
             cstr(json.dumps(preset_names, separators=(",", ":"))))
    h = []
    h.append("/* Generated by tools/gen/gen.py - do not edit. */")
    h.append("#ifndef AMINO_FACTORY_PRESETS_H")
    h.append("#define AMINO_FACTORY_PRESETS_H")
    h.append("#include <stdint.h>")
    h.append("typedef struct { uint16_t param; float value; } AminoPresetValue;")
    h.append("typedef struct { const char *name; const char *bank; const char *category;")
    h.append("                 const char *description; float bpm;")
    h.append("                 uint16_t value_count; const AminoPresetValue *values; } AminoFactoryPreset;")
    h.append("typedef struct { uint16_t preset; uint8_t layer; const char *label; } AminoLayerSource;")
    h.append("extern const AminoFactoryPreset amino_factory_presets[];")
    h.append("extern const int amino_factory_preset_count;")
    h.append("extern const AminoLayerSource amino_layer_sources[];")
    h.append("extern const int amino_layer_source_count;")
    h.append("extern const char amino_layer_src_list_json[];")
    h.append("extern const char amino_preset_list_json[];")
    h.append("#endif")
    with open(os.path.join(OUT, "factory_presets.c"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(c) + "\n")
    with open(os.path.join(OUT, "factory_presets.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(h) + "\n")
    print("presets:", len(presets))


def emit_wavetables():
    path = os.path.join(ROOT, "tools", "wavegen", "out", "amino_wavetables.bin")
    data = open(path, "rb").read()
    expected = len(P.TABLE_NAMES) * 64 * 128
    if len(data) != expected:
        raise SystemExit("wavetable bin is %d bytes, expected %d" % (len(data), expected))
    asset_dir = os.path.join(ROOT, "modules", "sound_generators", "amino",
                             "assets", "wave-previews")
    os.makedirs(asset_dir, exist_ok=True)
    for table in range(len(P.TABLE_NAMES)):
        preview = bytearray()
        for wave in range(64):
            start = (table * 64 + wave) * 128
            # Signed 8-bit pairs averaged, stored offset-binary (128 = zero).
            signed = [b - 256 if b > 127 else b for b in data[start:start + 128]]
            preview.extend(((signed[i] + signed[i + 1]) >> 1) + 128
                           for i in range(0, 128, 2))
        with open(os.path.join(asset_dir, "%02d.bin" % table), "wb") as f:
            f.write(preview)
    print("wave preview assets:", len(P.TABLE_NAMES), "tables x 64 waves x 64 samples")
    c = []
    c.append("/* Generated by tools/gen/gen.py from tools/wavegen/out/amino_wavetables.bin.")
    c.append("   %d tables x 64 waves x 128 samples, signed 8-bit. */" % len(P.TABLE_NAMES))
    c.append('#include "wavetables.h"')
    c.append("const signed char amino_wavetable_data[AMINO_NUM_TABLES][64][128] = {")
    pos = 0
    for t in range(len(P.TABLE_NAMES)):
        c.append("  {")
        for w in range(64):
            row = data[pos:pos + 128]
            pos += 128
            c.append("    { " + ",".join(str(b - 256 if b > 127 else b) for b in row) + " },")
        c.append("  },")
    c.append("};")
    h = ["/* Generated by tools/gen/gen.py - do not edit. */",
         "#ifndef AMINO_WAVETABLES_H",
         "#define AMINO_WAVETABLES_H",
         "#include \"params_gen.h\"",
         "extern const signed char amino_wavetable_data[AMINO_NUM_TABLES][64][128];",
         "#endif"]
    with open(os.path.join(OUT, "wavetables.c"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(c) + "\n")
    with open(os.path.join(OUT, "wavetables.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(h) + "\n")
    print("wavetables:", len(P.TABLE_NAMES))


