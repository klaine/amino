def fx_defaults():
    """FX_DEFAULTS rows from src/dsp/fx.c, so the UI resets to what the DSP loads."""
    text = open(os.path.join(OUT, "fx.c"), encoding="utf-8").read()
    body = text[text.index("FX_DEFAULTS[12][6] = {"):]
    body = body[:body.index("};")]
    rows = [[float(v.rstrip("f")) for v in re.findall(r"-?[0-9.]+f?", r)]
            for r in re.findall(r"\{([^{}]*)\}", body)]
    if len(rows) != len(P.FX_TYPES) or any(len(r) != 6 for r in rows):
        raise SystemExit("could not parse FX_DEFAULTS from fx.c")
    return rows


def ui_param(p, scope):
    d = {"name": p["name"], "short": p["short"], "type": p["kind"],
         "scope": scope, "default": p["default"]}
    if p["kind"] == "enum":
        d["options"] = list(p["opts"])
    else:
        d["min"] = p.get("mn", 0)
        d["max"] = p.get("mx", 1)
        if p.get("step") is not None:
            d["step"] = p["step"]
    if p.get("unit"):
        d["unit"] = p["unit"]
    if p["key"] in P.DISPLAY:
        d["display"] = P.DISPLAY[p["key"]]
    return d


def ui_meta(rows):
    """assets/ui_meta.json: everything the Remote UI needs to label, range,
    format and default a control, from the same source as the C tables.
    The preset lists go to assets/ui_presets.json (see emit_web_ui)."""
    params = {p["key"]: ui_param(p, "global") for p in P.GLOBAL}
    params.update({p["key"]: ui_param(p, "layer") for p in P.LAYER})
    defaults = fx_defaults()
    fx = {}
    for t, name in enumerate(P.FX_TYPES):
        if name == "Off":
            continue
        knobs = []
        for i, k in enumerate(P.FX_PARAMS[name]):
            k = dict(k, default=defaults[t][i])
            knobs.append(k)
        fx[name] = knobs
    # Option lists shared by several params (matrix sources/targets, tables,
    # on/off...) are stored once; src/web/store.js expandMeta() restores them.
    uses = {}
    for d in params.values():
        if "options" in d:
            uses.setdefault(tuple(d["options"]), []).append(d)
    option_lists = []
    for opts, ds in uses.items():
        if len(ds) > 1:
            for d in ds:
                d["optionsRef"] = len(option_lists)
                del d["options"]
            option_lists.append(list(opts))
    return {
        "version": 2,
        "optionLists": option_lists,
        "params": params,
        "layerKeys": [p["key"] for p in P.LAYER],
        "fx": fx,
        "modTargetKeys": P.MOD_TARGET_KEYS,
        "modTargetScale": P.MOD_TARGET_SCALE,
        "modSources": [{"bipolar": name in P.MOD_SOURCE_BIPOLAR,
                        "group": P.MOD_SOURCE_GROUP.get(name, "perf")}
                       for name in P.MOD_SOURCES],
        "presetCount": len(rows),
    }


CARD_META_BEGIN = "  /* BEGIN GENERATED CARD_META (tools/gen/gen.py) */"
CARD_META_END = "  /* END GENERATED CARD_META */"


def emit_card_meta():
    """Refresh the generated block in src/cards.js: FX knob labels and value
    curves per type, and the matrix option names, so on-device cards show the
    same real units as the Remote UI without reading anything on draw."""
    fx = [None]
    for name in P.FX_TYPES[1:]:
        knobs = []
        for k in P.FX_PARAMS[name]:
            row = ["Curve" if k["short"] == "Type" else k["name"]]
            if "options" in k:
                row += ["opts", k["options"]]
            else:
                d = k["display"]
                row += [d["kind"]] + ([d["lo"], d["hi"], d.get("unit", "")]
                                      if d["kind"] != "percent" else [])
            knobs.append(row)
        fx.append(knobs)
    meta = {"fxTypes": P.FX_TYPES, "fx": fx,
            "sources": P.MOD_SOURCES, "targets": P.MOD_TARGETS}
    path = os.path.join(ROOT, "src", "cards.js")
    with open(path, "r", encoding="utf-8") as f:
        text = f.read()
    a, b = text.index(CARD_META_BEGIN), text.index(CARD_META_END)
    block = "%s\n  var META = %s;\n" % (
        CARD_META_BEGIN, json.dumps(meta, separators=(",", ":"), ensure_ascii=True))
    text = text[:a] + block + text[b:]
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def emit_device_ui():
    """Copy the custom on-device UI entry points beside the packaged module."""
    module_dir = os.path.join(ROOT, "modules", "sound_generators", "amino")
    os.makedirs(module_dir, exist_ok=True)
    for name in ("ui_chain.js", "mod_matrix_ui.mjs", "cards.js", "help.json"):
        source = os.path.join(ROOT, "src", name)
        if os.path.exists(source):
            with open(source, "r", encoding="utf-8") as f:
                text = f.read()
            with open(os.path.join(module_dir, name), "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
    with open(os.path.join(ROOT, "src", "module.json"), "r", encoding="utf-8") as f:
        module_json = f.read()
    with open(os.path.join(module_dir, "module.json"), "w", encoding="utf-8", newline="\n") as f:
        f.write(module_json)


