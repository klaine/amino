def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def fmt_default(p):
    if p["kind"] == "enum":
        return "%d.0f" % p["default"]
    if p["kind"] == "int":
        return "%d.0f" % p["default"]
    return ("%.6ff" % p["default"])


def fmt_fnum(v):
    return ("%.6ff" % float(v))


def enum_range(p):
    """Enums are stored as option indices, so their numeric range is derived
    from the option list rather than the documented display range."""
    if p["kind"] == "enum":
        return 0, len(p["opts"]) - 1
    return p.get("mn", 0), p.get("mx", 1)


def viz_flags(p):
    v = p.get("viz")
    if not v:
        return ""
    return v


def emit_params():
    h = []
    h.append("/* Generated by tools/gen/gen.py - do not edit. */")
